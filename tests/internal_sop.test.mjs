import test from 'node:test';
import assert from 'node:assert/strict';
import { NextRequest } from 'next/server';
import { Database, db } from '../services/database/db.ts';
import { INTERNAL_SOP_EXAMPLES, findInternalSopExample, internalSopKey } from '../services/translation/internal-sop.ts';
import { buildStructuredPrompt } from '../services/translation/context.ts';
import { insertPastedText, WorkspaceRequestGate } from '../services/translation/workspace-input.ts';
import { GoogleTranslationProvider } from '../services/translation/google.ts';
import { validateTranslationTerminology } from '../services/terminology/validator.ts';
import { polishSopText } from '../services/translation/sop-polisher.ts';
import { POST as translate } from '../app/api/translate/route.ts';
import { POST as saveExample } from '../app/api/translation-examples/route.ts';

const req = (path, body) => new NextRequest(`http://localhost/api/${path}`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(body) });

test('Approved internal remarks are reused verbatim, not regenerated by the provider', async (t) => {
  t.mock.method(GoogleTranslationProvider.prototype, 'translate', () => { throw new Error('An approved example must not call AI'); });
  const sourceText = INTERNAL_SOP_EXAMPLES.map((e) => e.sourceText).join('\n');
  const response = await translate(req('translate', { sourceText, sourceLanguage: 'vi', targetLanguage: 'en', provider: 'google_translate' }));
  const result = await response.json();
  assert.equal(response.status, 200);
  assert.equal(result.translatedText, INTERNAL_SOP_EXAMPLES.map((e) => e.translatedText).join('\n'));
  assert.equal(result.provider, 'Mẫu nội bộ đã duyệt');
  assert.equal(result.approvedInternalExample, true);
});

test('Sentence memory preserves changed specifications, prohibitions and repeat counts', () => {
  const example = { id: 'spec', sourceText: 'Không được cao hơn 2mm.', translatedText: 'Must not exceed 2mm.', sourceLanguage: 'vi', targetLanguage: 'en' };
  assert.equal(findInternalSopExample('  Không  được cao hơn 2mm. ', [example]), example.translatedText);
  assert.equal(findInternalSopExample('Không được cao hơn 3mm.', [example]), undefined);
  assert.equal(findInternalSopExample('Được cao hơn 2mm.', [example]), undefined);
  assert.equal(findInternalSopExample(`${example.sourceText}\n${example.sourceText}`, [example]), `${example.translatedText}\n${example.translatedText}`);
});

test('Explicitly saved examples persist across database connections and override built-in wording', async () => {
  const sourceText = INTERNAL_SOP_EXAMPLES[0].sourceText;
  const translatedText = 'Keep the approved internal thread instruction.';
  const response = await saveExample(req('translation-examples', { sourceText, translatedText, sourceLanguage: 'vi', targetLanguage: 'en' }));
  assert.equal(response.status, 200);
  const secondConnection = new Database();
  const examples = [...secondConnection.getInternalSopExamples('vi', 'en'), ...INTERNAL_SOP_EXAMPLES];
  assert.equal(findInternalSopExample(sourceText, examples), translatedText);
  assert.equal(secondConnection.getInternalSopExamples('en', 'vi').length, 0);
});

test('Saving a sentence requires a real target and never accepts an identical source', async () => {
  for (const translatedText of ['', 'Kiểm tra mẫu.']) {
    const response = await saveExample(req('translation-examples', { sourceText: 'Kiểm tra mẫu.', translatedText, sourceLanguage: 'vi', targetLanguage: 'en' }));
    assert.equal(response.status, 400);
  }
});

test('The standard text prompt uses shop-floor instructions and protects all conditions', () => {
  const prompt = buildStructuredPrompt({ sourceText: 'Quét keo và dán đế bằng đường mài, không được cao hay thấp hơn 2mm.', sourceLanguage: 'vi', targetLanguage: 'en', approvedTerminology: db.getApprovedTerminology('vi', 'en') });
  assert.match(prompt.systemPrompt, /INTERNAL FACTORY SOP STYLE/);
  assert.match(prompt.systemPrompt, /BOTH limits/);
  assert.match(prompt.systemPrompt, /Never shorten by dropping content/);
  assert.doesNotMatch(prompt.systemPrompt, /remove redundant wording and repeated ideas|40.60%/);
  assert.match(prompt.userPrompt, /attach the outsole/);
});

test('An approved action form satisfies the process term without allowing an unrelated synonym', () => {
  const glossary = [{ id: 'attach', sourceTerm: 'Dán đế', targetTerm: 'Bottom attaching', sourceLanguage: 'vi', targetLanguage: 'en', status: 'approved', priority: 1, createdAt: '', updatedAt: '' }];
  assert.equal(validateTranslationTerminology('Dán đế theo đường mài.', 'Attach the outsole along the buffing line.', glossary).isValid, true);
  assert.equal(validateTranslationTerminology('Dán đế theo đường mài.', 'Handle the shoe along the buffing line.', glossary).isValid, false);
});

test('Paste inserts once, replaces only the selected span and retains its cursor', () => {
  assert.deepEqual(insertPastedText('', 'Kiểm tra mẫu.', 0, 0), { text: 'Kiểm tra mẫu.', caret: 13 });
  assert.deepEqual(insertPastedText('A old Z', 'new', 2, 5), { text: 'A new Z', caret: 5 });
});

test('Concise wording uses a grammatical condition and retains the operation and both limits', () => {
  const result = polishSopText('Tuck excess thread inside the outsole to minimize thread expose. Keep cementing level with the buffing line, not higher or lower.');
  assert.match(result, /minimize exposed threads/);
  assert.match(result, /inside the outsole/);
  assert.match(result, /not higher or lower/);
});

test('Editing, clearing and a newer request invalidate older responses even if transport still resolves', () => {
  const gate = new WorkspaceRequestGate();
  const first = gate.begin();
  const second = gate.begin();
  assert.equal(first.signal.aborted, true);
  assert.equal(gate.isCurrent(first), false);
  assert.equal(gate.isCurrent(second), true);
  gate.cancel();
  assert.equal(gate.isCurrent(second), false);
  assert.notEqual(internalSopKey('2mm'), internalSopKey('3mm'));
});
